CREATE TABLE commandes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero VARCHAR(50) NOT NULL,
    table_id BIGINT NOT NULL,
    client_id BIGINT,
    cree_par_id BIGINT NOT NULL,
    statut VARCHAR(20) NOT NULL,
    montant_total NUMERIC(12,2) NOT NULL DEFAULT 0,
    confirmee_le TIMESTAMPTZ,
    annulee_le TIMESTAMPTZ,
    cree_le TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    modifie_le TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_commandes_numero UNIQUE (numero),
    CONSTRAINT fk_commandes_table FOREIGN KEY (table_id)
        REFERENCES tables_restaurant (id) ON DELETE RESTRICT,
    CONSTRAINT fk_commandes_client FOREIGN KEY (client_id)
        REFERENCES clients (id) ON DELETE RESTRICT,
    CONSTRAINT fk_commandes_createur FOREIGN KEY (cree_par_id)
        REFERENCES utilisateurs (id) ON DELETE RESTRICT,
    CONSTRAINT ck_commandes_statut CHECK (statut IN ('BROUILLON', 'CONFIRMEE', 'ANNULEE')),
    CONSTRAINT ck_commandes_total_non_negatif CHECK (montant_total >= 0),
    CONSTRAINT ck_commandes_version_positive CHECK (version >= 0),
    CONSTRAINT ck_commandes_dates_statut CHECK (
        (statut = 'BROUILLON' AND confirmee_le IS NULL AND annulee_le IS NULL)
        OR (statut = 'CONFIRMEE' AND confirmee_le IS NOT NULL AND annulee_le IS NULL)
        OR (statut = 'ANNULEE' AND annulee_le IS NOT NULL)
    )
);

CREATE INDEX idx_commandes_statut ON commandes (statut);
CREATE INDEX idx_commandes_table ON commandes (table_id);
CREATE INDEX idx_commandes_client ON commandes (client_id);
CREATE INDEX idx_commandes_createur ON commandes (cree_par_id);
CREATE INDEX idx_commandes_date ON commandes (cree_le DESC);

CREATE TABLE lignes_commande (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    commande_id BIGINT NOT NULL,
    produit_id BIGINT NOT NULL,
    quantite INTEGER NOT NULL,
    prix_unitaire NUMERIC(12,2) NOT NULL,
    sous_total NUMERIC(12,2) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_lignes_commande FOREIGN KEY (commande_id)
        REFERENCES commandes (id) ON DELETE CASCADE,
    CONSTRAINT fk_lignes_produit FOREIGN KEY (produit_id)
        REFERENCES produits (id) ON DELETE RESTRICT,
    CONSTRAINT uk_lignes_commande_produit UNIQUE (commande_id, produit_id),
    CONSTRAINT ck_lignes_quantite_positive CHECK (quantite > 0),
    CONSTRAINT ck_lignes_prix_positif CHECK (prix_unitaire > 0),
    CONSTRAINT ck_lignes_sous_total_positif CHECK (sous_total > 0),
    CONSTRAINT ck_lignes_version_positive CHECK (version >= 0)
);

CREATE INDEX idx_lignes_commande ON lignes_commande (commande_id);
CREATE INDEX idx_lignes_produit ON lignes_commande (produit_id);

