ALTER TABLE lignes_commande
    ADD COLUMN remarque VARCHAR(500);

ALTER TABLE commandes
    ADD COLUMN preparation_commencee_le TIMESTAMPTZ,
    ADD COLUMN prete_le TIMESTAMPTZ;

ALTER TABLE commandes DROP CONSTRAINT ck_commandes_statut;
ALTER TABLE commandes DROP CONSTRAINT ck_commandes_dates_statut;

ALTER TABLE commandes
    ADD CONSTRAINT ck_commandes_statut
        CHECK (statut IN ('BROUILLON', 'CONFIRMEE', 'EN_PREPARATION', 'PRETE', 'ANNULEE')),
    ADD CONSTRAINT ck_commandes_dates_statut CHECK (
        (statut = 'BROUILLON' AND confirmee_le IS NULL AND annulee_le IS NULL
            AND preparation_commencee_le IS NULL AND prete_le IS NULL)
        OR (statut = 'CONFIRMEE' AND confirmee_le IS NOT NULL AND annulee_le IS NULL
            AND preparation_commencee_le IS NULL AND prete_le IS NULL)
        OR (statut = 'EN_PREPARATION' AND confirmee_le IS NOT NULL AND annulee_le IS NULL
            AND preparation_commencee_le IS NOT NULL AND prete_le IS NULL)
        OR (statut = 'PRETE' AND confirmee_le IS NOT NULL AND annulee_le IS NULL
            AND preparation_commencee_le IS NOT NULL AND prete_le IS NOT NULL)
        OR (statut = 'ANNULEE' AND annulee_le IS NOT NULL
            AND preparation_commencee_le IS NULL AND prete_le IS NULL)
    );

CREATE TABLE notifications_internes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    commande_id BIGINT NOT NULL,
    type VARCHAR(50) NOT NULL,
    message VARCHAR(255) NOT NULL,
    lue BOOLEAN NOT NULL DEFAULT FALSE,
    cree_le TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_notifications_commande FOREIGN KEY (commande_id)
        REFERENCES commandes (id) ON DELETE RESTRICT,
    CONSTRAINT uk_notifications_commande_type UNIQUE (commande_id, type),
    CONSTRAINT ck_notifications_type CHECK (type IN ('COMMANDE_PRETE')),
    CONSTRAINT ck_notifications_version_positive CHECK (version >= 0)
);

CREATE INDEX idx_notifications_non_lues
    ON notifications_internes (lue, cree_le DESC);

