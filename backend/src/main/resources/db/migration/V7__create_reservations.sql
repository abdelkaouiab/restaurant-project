CREATE TABLE reservations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero VARCHAR(50) NOT NULL,
    table_id BIGINT NOT NULL,
    client_id BIGINT NOT NULL,
    cree_par_id BIGINT NOT NULL,
    nombre_personnes INTEGER NOT NULL,
    debut TIMESTAMPTZ NOT NULL,
    fin TIMESTAMPTZ NOT NULL,
    statut VARCHAR(20) NOT NULL,
    remarques VARCHAR(500),
    cree_le TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    modifie_le TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_reservations_numero UNIQUE (numero),
    CONSTRAINT fk_reservations_table FOREIGN KEY (table_id)
        REFERENCES tables_restaurant (id) ON DELETE RESTRICT,
    CONSTRAINT fk_reservations_client FOREIGN KEY (client_id)
        REFERENCES clients (id) ON DELETE RESTRICT,
    CONSTRAINT fk_reservations_createur FOREIGN KEY (cree_par_id)
        REFERENCES utilisateurs (id) ON DELETE RESTRICT,
    CONSTRAINT ck_reservations_personnes CHECK (nombre_personnes > 0),
    CONSTRAINT ck_reservations_duree CHECK (fin = debut + INTERVAL '2 hours'),
    CONSTRAINT ck_reservations_statut CHECK (
        statut IN ('EN_ATTENTE', 'CONFIRMEE', 'ARRIVEE', 'TERMINEE', 'ANNULEE', 'ABSENTE')
    ),
    CONSTRAINT ck_reservations_version_positive CHECK (version >= 0)
);

CREATE INDEX idx_reservations_table_creneau
    ON reservations (table_id, debut, fin);
CREATE INDEX idx_reservations_statut_debut
    ON reservations (statut, debut);
CREATE INDEX idx_reservations_client ON reservations (client_id);

ALTER TABLE commandes ADD COLUMN reservation_id BIGINT;
ALTER TABLE commandes
    ADD CONSTRAINT uk_commandes_reservation UNIQUE (reservation_id),
    ADD CONSTRAINT fk_commandes_reservation FOREIGN KEY (reservation_id)
        REFERENCES reservations (id) ON DELETE RESTRICT;

INSERT INTO permissions (nom, description)
VALUES ('RESERVATION_GERER', 'Créer et faire évoluer les réservations');

INSERT INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id
FROM roles r
JOIN permissions p ON p.nom = 'RESERVATION_GERER'
WHERE r.nom IN ('ADMINISTRATEUR', 'GERANT', 'SERVEUR');
