CREATE TABLE fournisseurs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(150) NOT NULL,
    email VARCHAR(254),
    telephone VARCHAR(30),
    adresse VARCHAR(500),
    actif BOOLEAN NOT NULL DEFAULT TRUE,
    cree_le TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    modifie_le TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_fournisseurs_nom UNIQUE (nom),
    CONSTRAINT uk_fournisseurs_email UNIQUE (email),
    CONSTRAINT ck_fournisseurs_version CHECK (version >= 0)
);
CREATE INDEX idx_fournisseurs_actif_nom ON fournisseurs (actif, nom);

CREATE TABLE achats (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero VARCHAR(50) NOT NULL,
    fournisseur_id BIGINT NOT NULL,
    cree_par_id BIGINT NOT NULL,
    statut VARCHAR(25) NOT NULL DEFAULT 'BROUILLON',
    montant_total NUMERIC(14,2) NOT NULL DEFAULT 0,
    commande_le TIMESTAMPTZ,
    recue_le TIMESTAMPTZ,
    annule_le TIMESTAMPTZ,
    cree_le TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    modifie_le TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_achats_numero UNIQUE (numero),
    CONSTRAINT fk_achats_fournisseur FOREIGN KEY (fournisseur_id) REFERENCES fournisseurs(id) ON DELETE RESTRICT,
    CONSTRAINT fk_achats_createur FOREIGN KEY (cree_par_id) REFERENCES utilisateurs(id) ON DELETE RESTRICT,
    CONSTRAINT ck_achats_statut CHECK (statut IN ('BROUILLON','COMMANDE','PARTIELLEMENT_RECU','RECU','ANNULE')),
    CONSTRAINT ck_achats_total CHECK (montant_total >= 0),
    CONSTRAINT ck_achats_version CHECK (version >= 0)
);
CREATE INDEX idx_achats_statut_date ON achats (statut, cree_le DESC);
CREATE INDEX idx_achats_fournisseur ON achats (fournisseur_id, cree_le DESC);

CREATE TABLE lignes_achat (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    achat_id BIGINT NOT NULL,
    ingredient_id BIGINT NOT NULL,
    quantite_commandee NUMERIC(14,3) NOT NULL,
    quantite_recue NUMERIC(14,3) NOT NULL DEFAULT 0,
    prix_unitaire NUMERIC(14,2) NOT NULL,
    sous_total NUMERIC(14,2) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_lignes_achat_achat FOREIGN KEY (achat_id) REFERENCES achats(id) ON DELETE CASCADE,
    CONSTRAINT fk_lignes_achat_ingredient FOREIGN KEY (ingredient_id) REFERENCES ingredients(id) ON DELETE RESTRICT,
    CONSTRAINT uk_lignes_achat_ingredient UNIQUE (achat_id, ingredient_id),
    CONSTRAINT ck_lignes_achat_quantite CHECK (quantite_commandee > 0 AND quantite_recue >= 0 AND quantite_recue <= quantite_commandee),
    CONSTRAINT ck_lignes_achat_prix CHECK (prix_unitaire > 0 AND sous_total > 0),
    CONSTRAINT ck_lignes_achat_version CHECK (version >= 0)
);
CREATE INDEX idx_lignes_achat_ingredient ON lignes_achat (ingredient_id);

CREATE TABLE receptions_achat (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    achat_id BIGINT NOT NULL,
    cle_idempotence UUID NOT NULL,
    signature_requete VARCHAR(1000) NOT NULL,
    recue_par_id BIGINT NOT NULL,
    cree_le TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_receptions_achat FOREIGN KEY (achat_id) REFERENCES achats(id) ON DELETE RESTRICT,
    CONSTRAINT fk_receptions_utilisateur FOREIGN KEY (recue_par_id) REFERENCES utilisateurs(id) ON DELETE RESTRICT,
    CONSTRAINT uk_receptions_idempotence UNIQUE (cle_idempotence)
);
CREATE INDEX idx_receptions_achat ON receptions_achat (achat_id, cree_le DESC);

CREATE TABLE lignes_reception_achat (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reception_id BIGINT NOT NULL,
    ligne_achat_id BIGINT NOT NULL,
    quantite NUMERIC(14,3) NOT NULL,
    CONSTRAINT fk_lignes_reception_reception FOREIGN KEY (reception_id) REFERENCES receptions_achat(id) ON DELETE RESTRICT,
    CONSTRAINT fk_lignes_reception_achat FOREIGN KEY (ligne_achat_id) REFERENCES lignes_achat(id) ON DELETE RESTRICT,
    CONSTRAINT uk_reception_ligne UNIQUE (reception_id, ligne_achat_id),
    CONSTRAINT ck_lignes_reception_quantite CHECK (quantite > 0)
);

