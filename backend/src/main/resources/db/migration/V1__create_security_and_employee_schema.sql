CREATE TABLE employes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricule VARCHAR(30) NOT NULL,
    nom VARCHAR(100) NOT NULL,
    prenom VARCHAR(100) NOT NULL,
    telephone VARCHAR(30),
    poste VARCHAR(100) NOT NULL,
    date_embauche DATE NOT NULL,
    actif BOOLEAN NOT NULL DEFAULT TRUE,
    cree_le TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    modifie_le TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_employes_matricule UNIQUE (matricule),
    CONSTRAINT ck_employes_matricule_non_vide CHECK (char_length(btrim(matricule)) > 0),
    CONSTRAINT ck_employes_nom_non_vide CHECK (char_length(btrim(nom)) > 0),
    CONSTRAINT ck_employes_prenom_non_vide CHECK (char_length(btrim(prenom)) > 0),
    CONSTRAINT ck_employes_poste_non_vide CHECK (char_length(btrim(poste)) > 0),
    CONSTRAINT ck_employes_telephone_non_vide CHECK (telephone IS NULL OR char_length(btrim(telephone)) > 0),
    CONSTRAINT ck_employes_version_positive CHECK (version >= 0)
);

CREATE INDEX idx_employes_nom_prenom ON employes (nom, prenom);
CREATE INDEX idx_employes_actif ON employes (actif);

CREATE TABLE utilisateurs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employe_id BIGINT NOT NULL,
    email VARCHAR(254) NOT NULL,
    mot_de_passe_hash VARCHAR(255) NOT NULL,
    actif BOOLEAN NOT NULL DEFAULT TRUE,
    cree_le TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    modifie_le TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_utilisateurs_employe UNIQUE (employe_id),
    CONSTRAINT fk_utilisateurs_employe
        FOREIGN KEY (employe_id) REFERENCES employes (id) ON DELETE RESTRICT,
    CONSTRAINT ck_utilisateurs_email_non_vide CHECK (char_length(btrim(email)) > 0),
    CONSTRAINT ck_utilisateurs_email_normalise CHECK (email = lower(btrim(email))),
    CONSTRAINT ck_utilisateurs_hash_non_vide CHECK (char_length(btrim(mot_de_passe_hash)) > 0),
    CONSTRAINT ck_utilisateurs_version_positive CHECK (version >= 0)
);

CREATE UNIQUE INDEX uk_utilisateurs_email_normalise ON utilisateurs (lower(email));
CREATE INDEX idx_utilisateurs_actif ON utilisateurs (actif);

CREATE TABLE roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(50) NOT NULL,
    description VARCHAR(255) NOT NULL,
    actif BOOLEAN NOT NULL DEFAULT TRUE,
    cree_le TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    modifie_le TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_roles_nom UNIQUE (nom),
    CONSTRAINT ck_roles_nom_non_vide CHECK (char_length(btrim(nom)) > 0),
    CONSTRAINT ck_roles_description_non_vide CHECK (char_length(btrim(description)) > 0),
    CONSTRAINT ck_roles_version_positive CHECK (version >= 0)
);

CREATE INDEX idx_roles_actif ON roles (actif);

CREATE TABLE permissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(80) NOT NULL,
    description VARCHAR(255) NOT NULL,
    actif BOOLEAN NOT NULL DEFAULT TRUE,
    cree_le TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    modifie_le TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_permissions_nom UNIQUE (nom),
    CONSTRAINT ck_permissions_nom_non_vide CHECK (char_length(btrim(nom)) > 0),
    CONSTRAINT ck_permissions_description_non_vide CHECK (char_length(btrim(description)) > 0),
    CONSTRAINT ck_permissions_version_positive CHECK (version >= 0)
);

CREATE INDEX idx_permissions_actif ON permissions (actif);

CREATE TABLE utilisateur_roles (
    utilisateur_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL,
    CONSTRAINT pk_utilisateur_roles PRIMARY KEY (utilisateur_id, role_id),
    CONSTRAINT fk_utilisateur_roles_utilisateur
        FOREIGN KEY (utilisateur_id) REFERENCES utilisateurs (id) ON DELETE CASCADE,
    CONSTRAINT fk_utilisateur_roles_role
        FOREIGN KEY (role_id) REFERENCES roles (id) ON DELETE RESTRICT
);

CREATE INDEX idx_utilisateur_roles_role ON utilisateur_roles (role_id);

CREATE TABLE role_permissions (
    role_id BIGINT NOT NULL,
    permission_id BIGINT NOT NULL,
    CONSTRAINT pk_role_permissions PRIMARY KEY (role_id, permission_id),
    CONSTRAINT fk_role_permissions_role
        FOREIGN KEY (role_id) REFERENCES roles (id) ON DELETE CASCADE,
    CONSTRAINT fk_role_permissions_permission
        FOREIGN KEY (permission_id) REFERENCES permissions (id) ON DELETE RESTRICT
);

CREATE INDEX idx_role_permissions_permission ON role_permissions (permission_id);

CREATE TABLE journaux_activite (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id BIGINT,
    action VARCHAR(100) NOT NULL,
    type_ressource VARCHAR(100) NOT NULL,
    ressource_id VARCHAR(100),
    resultat VARCHAR(20) NOT NULL,
    details VARCHAR(1000),
    adresse_ip VARCHAR(45),
    correlation_id UUID NOT NULL,
    cree_le TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_journaux_activite_utilisateur
        FOREIGN KEY (utilisateur_id) REFERENCES utilisateurs (id) ON DELETE SET NULL,
    CONSTRAINT ck_journaux_action_non_vide CHECK (char_length(btrim(action)) > 0),
    CONSTRAINT ck_journaux_type_ressource_non_vide CHECK (char_length(btrim(type_ressource)) > 0),
    CONSTRAINT ck_journaux_ressource_id_non_vide CHECK (
        ressource_id IS NULL OR char_length(btrim(ressource_id)) > 0
    ),
    CONSTRAINT ck_journaux_resultat CHECK (resultat IN ('SUCCES', 'ECHEC')),
    CONSTRAINT ck_journaux_details_non_vides CHECK (details IS NULL OR char_length(btrim(details)) > 0),
    CONSTRAINT ck_journaux_adresse_ip_non_vide CHECK (
        adresse_ip IS NULL OR char_length(btrim(adresse_ip)) > 0
    )
);

CREATE INDEX idx_journaux_utilisateur_date ON journaux_activite (utilisateur_id, cree_le DESC);
CREATE INDEX idx_journaux_correlation ON journaux_activite (correlation_id);
CREATE INDEX idx_journaux_ressource ON journaux_activite (type_ressource, ressource_id);
CREATE INDEX idx_journaux_date ON journaux_activite (cree_le DESC);
