CREATE TABLE ingredients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(150) NOT NULL,
    unite VARCHAR(20) NOT NULL,
    quantite_disponible NUMERIC(14,3) NOT NULL DEFAULT 0,
    seuil_alerte NUMERIC(14,3) NOT NULL DEFAULT 0,
    actif BOOLEAN NOT NULL DEFAULT TRUE,
    cree_le TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    modifie_le TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_ingredients_nom UNIQUE (nom),
    CONSTRAINT ck_ingredients_unite CHECK (unite IN ('GRAMME','KILOGRAMME','MILLILITRE','LITRE','UNITE')),
    CONSTRAINT ck_ingredients_seuil CHECK (seuil_alerte >= 0),
    CONSTRAINT ck_ingredients_version CHECK (version >= 0)
);
CREATE INDEX idx_ingredients_actif_nom ON ingredients (actif, nom);
CREATE INDEX idx_ingredients_stock_faible ON ingredients (quantite_disponible, seuil_alerte) WHERE actif = TRUE;

CREATE TABLE produit_ingredients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produit_id BIGINT NOT NULL,
    ingredient_id BIGINT NOT NULL,
    quantite NUMERIC(14,3) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_recettes_produit FOREIGN KEY (produit_id) REFERENCES produits(id) ON DELETE RESTRICT,
    CONSTRAINT fk_recettes_ingredient FOREIGN KEY (ingredient_id) REFERENCES ingredients(id) ON DELETE RESTRICT,
    CONSTRAINT uk_recettes_produit_ingredient UNIQUE (produit_id, ingredient_id),
    CONSTRAINT ck_recettes_quantite CHECK (quantite > 0),
    CONSTRAINT ck_recettes_version CHECK (version >= 0)
);
CREATE INDEX idx_recettes_ingredient ON produit_ingredients (ingredient_id);

CREATE TABLE mouvements_stock (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ingredient_id BIGINT NOT NULL,
    utilisateur_id BIGINT,
    commande_id BIGINT,
    cle_idempotence UUID,
    type VARCHAR(20) NOT NULL,
    quantite NUMERIC(14,3) NOT NULL,
    variation NUMERIC(14,3) NOT NULL,
    quantite_apres NUMERIC(14,3) NOT NULL,
    motif VARCHAR(500),
    cree_le TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_mouvements_ingredient FOREIGN KEY (ingredient_id) REFERENCES ingredients(id) ON DELETE RESTRICT,
    CONSTRAINT fk_mouvements_utilisateur FOREIGN KEY (utilisateur_id) REFERENCES utilisateurs(id) ON DELETE RESTRICT,
    CONSTRAINT fk_mouvements_commande FOREIGN KEY (commande_id) REFERENCES commandes(id) ON DELETE RESTRICT,
    CONSTRAINT uk_mouvements_idempotence UNIQUE (cle_idempotence),
    CONSTRAINT uk_mouvements_commande_ingredient UNIQUE (commande_id, ingredient_id),
    CONSTRAINT ck_mouvements_type CHECK (type IN ('ENTREE','SORTIE','AJUSTEMENT','PERTE','RETOUR')),
    CONSTRAINT ck_mouvements_quantite CHECK (quantite > 0),
    CONSTRAINT ck_mouvements_motif CHECK (type NOT IN ('AJUSTEMENT','PERTE') OR length(trim(motif)) > 0),
    CONSTRAINT ck_mouvements_variation CHECK (variation <> 0)
);
CREATE INDEX idx_mouvements_ingredient_date ON mouvements_stock (ingredient_id, cree_le DESC);
CREATE INDEX idx_mouvements_commande ON mouvements_stock (commande_id) WHERE commande_id IS NOT NULL;

