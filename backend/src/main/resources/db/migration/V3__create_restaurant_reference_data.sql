CREATE TABLE clients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(100) NOT NULL,
    prenom VARCHAR(100) NOT NULL,
    email VARCHAR(254),
    telephone VARCHAR(30),
    actif BOOLEAN NOT NULL DEFAULT TRUE,
    cree_le TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    modifie_le TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ck_clients_nom_non_vide CHECK (char_length(btrim(nom)) > 0),
    CONSTRAINT ck_clients_prenom_non_vide CHECK (char_length(btrim(prenom)) > 0),
    CONSTRAINT ck_clients_email_non_vide CHECK (email IS NULL OR char_length(btrim(email)) > 0),
    CONSTRAINT ck_clients_telephone_non_vide CHECK (telephone IS NULL OR char_length(btrim(telephone)) > 0),
    CONSTRAINT ck_clients_version_positive CHECK (version >= 0)
);

CREATE INDEX idx_clients_nom_prenom ON clients (nom, prenom);
CREATE INDEX idx_clients_email ON clients (lower(email));
CREATE INDEX idx_clients_telephone ON clients (telephone);
CREATE INDEX idx_clients_actif ON clients (actif);

CREATE TABLE tables_restaurant (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero INTEGER NOT NULL,
    capacite INTEGER NOT NULL,
    actif BOOLEAN NOT NULL DEFAULT TRUE,
    cree_le TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    modifie_le TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_tables_restaurant_numero UNIQUE (numero),
    CONSTRAINT ck_tables_restaurant_numero_positif CHECK (numero > 0),
    CONSTRAINT ck_tables_restaurant_capacite_positive CHECK (capacite > 0),
    CONSTRAINT ck_tables_restaurant_version_positive CHECK (version >= 0)
);

CREATE INDEX idx_tables_restaurant_actif ON tables_restaurant (actif);

CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(100) NOT NULL,
    description VARCHAR(500),
    actif BOOLEAN NOT NULL DEFAULT TRUE,
    cree_le TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    modifie_le TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ck_categories_nom_non_vide CHECK (char_length(btrim(nom)) > 0),
    CONSTRAINT ck_categories_description_non_vide CHECK (
        description IS NULL OR char_length(btrim(description)) > 0
    ),
    CONSTRAINT ck_categories_version_positive CHECK (version >= 0)
);

CREATE UNIQUE INDEX uk_categories_nom_normalise ON categories (lower(btrim(nom)));
CREATE INDEX idx_categories_actif ON categories (actif);

CREATE TABLE produits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categorie_id BIGINT NOT NULL,
    nom VARCHAR(150) NOT NULL,
    description VARCHAR(1000),
    prix NUMERIC(12,2) NOT NULL,
    actif BOOLEAN NOT NULL DEFAULT TRUE,
    cree_le TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    modifie_le TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_produits_categorie
        FOREIGN KEY (categorie_id) REFERENCES categories (id) ON DELETE RESTRICT,
    CONSTRAINT ck_produits_nom_non_vide CHECK (char_length(btrim(nom)) > 0),
    CONSTRAINT ck_produits_description_non_vide CHECK (
        description IS NULL OR char_length(btrim(description)) > 0
    ),
    CONSTRAINT ck_produits_prix_positif CHECK (prix > 0),
    CONSTRAINT ck_produits_version_positive CHECK (version >= 0)
);

CREATE INDEX idx_produits_nom ON produits (lower(nom));
CREATE INDEX idx_produits_categorie ON produits (categorie_id);
CREATE INDEX idx_produits_actif ON produits (actif);

