ALTER TABLE commandes ADD COLUMN payee_le TIMESTAMPTZ;
ALTER TABLE commandes DROP CONSTRAINT ck_commandes_statut;
ALTER TABLE commandes DROP CONSTRAINT ck_commandes_dates_statut;

ALTER TABLE commandes
    ADD CONSTRAINT ck_commandes_statut
        CHECK (statut IN ('BROUILLON', 'CONFIRMEE', 'EN_PREPARATION', 'PRETE', 'PAYEE', 'ANNULEE')),
    ADD CONSTRAINT ck_commandes_dates_statut CHECK (
        (statut = 'BROUILLON' AND confirmee_le IS NULL AND annulee_le IS NULL
            AND preparation_commencee_le IS NULL AND prete_le IS NULL AND payee_le IS NULL)
        OR (statut = 'CONFIRMEE' AND confirmee_le IS NOT NULL AND annulee_le IS NULL
            AND preparation_commencee_le IS NULL AND prete_le IS NULL AND payee_le IS NULL)
        OR (statut = 'EN_PREPARATION' AND confirmee_le IS NOT NULL AND annulee_le IS NULL
            AND preparation_commencee_le IS NOT NULL AND prete_le IS NULL AND payee_le IS NULL)
        OR (statut = 'PRETE' AND confirmee_le IS NOT NULL AND annulee_le IS NULL
            AND preparation_commencee_le IS NOT NULL AND prete_le IS NOT NULL AND payee_le IS NULL)
        OR (statut = 'PAYEE' AND confirmee_le IS NOT NULL AND annulee_le IS NULL
            AND preparation_commencee_le IS NOT NULL AND prete_le IS NOT NULL
            AND payee_le IS NOT NULL)
        OR (statut = 'ANNULEE' AND annulee_le IS NOT NULL
            AND preparation_commencee_le IS NULL AND prete_le IS NULL AND payee_le IS NULL)
    );

CREATE TABLE paiements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    commande_id BIGINT NOT NULL,
    encaisse_par_id BIGINT NOT NULL,
    cle_idempotence UUID NOT NULL,
    montant NUMERIC(12,2) NOT NULL,
    mode VARCHAR(30) NOT NULL,
    statut VARCHAR(20) NOT NULL,
    cree_le TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_paiements_commande FOREIGN KEY (commande_id)
        REFERENCES commandes (id) ON DELETE RESTRICT,
    CONSTRAINT fk_paiements_caissier FOREIGN KEY (encaisse_par_id)
        REFERENCES utilisateurs (id) ON DELETE RESTRICT,
    CONSTRAINT uk_paiements_idempotence UNIQUE (cle_idempotence),
    CONSTRAINT ck_paiements_montant_positif CHECK (montant > 0),
    CONSTRAINT ck_paiements_mode CHECK (mode IN ('ESPECES', 'CARTE', 'CHEQUE', 'TITRE_RESTAURANT')),
    CONSTRAINT ck_paiements_statut CHECK (statut IN ('VALIDE')),
    CONSTRAINT ck_paiements_version_positive CHECK (version >= 0)
);

CREATE INDEX idx_paiements_commande ON paiements (commande_id, statut);
CREATE INDEX idx_paiements_date ON paiements (cree_le DESC);

CREATE TABLE factures (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    commande_id BIGINT NOT NULL,
    numero VARCHAR(50) NOT NULL,
    montant_total NUMERIC(12,2) NOT NULL,
    emise_le TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_factures_commande UNIQUE (commande_id),
    CONSTRAINT uk_factures_numero UNIQUE (numero),
    CONSTRAINT fk_factures_commande FOREIGN KEY (commande_id)
        REFERENCES commandes (id) ON DELETE RESTRICT,
    CONSTRAINT ck_factures_montant_positif CHECK (montant_total > 0),
    CONSTRAINT ck_factures_version_positive CHECK (version >= 0)
);

CREATE INDEX idx_factures_date ON factures (emise_le DESC);

